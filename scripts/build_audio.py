"""Build bundled Japanese MP3s locally; text is never sent to a TTS service.

Requires pyopenjtalk-plus, numpy, imageio-ffmpeg and Playwright.
Usage: python scripts/build_audio.py [--limit N] [--collect-only]
"""
import argparse, hashlib, io, json, subprocess, sys, wave
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'.tools'))
from playwright.sync_api import sync_playwright

def collect():
    with sync_playwright() as p:
        browser=p.chromium.launch(channel='msedge',headless=True)
        page=browser.new_page()
        page.route('https://**/*',lambda route:route.abort())
        page.goto((ROOT/'index.html').as_uri())
        result=page.evaluate('''() => {
          const clean=StudyAudio.clean;
          const texts=RAW_VOCAB.map(w=>w.h).concat(GRAMMAR_DATA.units.map(u=>u.example.kana));
          READINGS.forEach(r=>r.blocks.forEach(tokens=>{
            const dialogue=typeof tokens[0]==='string'&&/^[AB]$/.test(tokens[0]);
            const text=(dialogue?tokens.slice(2):tokens).map(t=>typeof t==='number'?READING_LEXICON[t].h:t).join('').replace(/[（）「」／—]/g,'');
            (text.match(/[^。！？]+[。！？]?/g)||[]).forEach(t=>texts.push(t));
          }));
          return [...new Set(texts.map(clean).filter(Boolean))].sort();
        }''')
        browser.close()
    return result

def build(texts,limit):
    import imageio_ffmpeg, numpy as np, pyopenjtalk
    folder=ROOT/'assets/audio';folder.mkdir(parents=True,exist_ok=True)
    mapping={text:hashlib.sha256(text.encode()).hexdigest()[:20]+'.mp3' for text in texts}
    pending=[(text,name) for text,name in mapping.items() if not (folder/name).exists() or (folder/name).stat().st_size<500]
    if limit:pending=pending[:limit]
    failures=[];encoder=imageio_ffmpeg.get_ffmpeg_exe()
    for completed,(text,name) in enumerate(pending,1):
        try:
            samples,rate=pyopenjtalk.tts(text,use_sudachi_kanji_yomi=False,predict_nani=False)
            peak=float(np.max(np.abs(samples)))
            if not peak:raise ValueError('Silent recording')
            pcm=np.clip(samples*(26000/peak),-32768,32767).astype('<i2')
            buffer=io.BytesIO()
            with wave.open(buffer,'wb') as out:
                out.setnchannels(1);out.setsampwidth(2);out.setframerate(rate);out.writeframes(pcm.tobytes())
            result=subprocess.run([encoder,'-v','error','-y','-i','pipe:0','-ac','1','-ar','24000','-codec:a','libmp3lame','-b:a','48k',str(folder/name)],input=buffer.getvalue(),capture_output=True,creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))
            if result.returncode:raise ValueError(result.stderr.decode(errors='replace'))
        except Exception as error:failures.append((name,str(error)))
        if completed%25==0:print(f'Audio {completed}/{len(pending)}; failures={len(failures)}',flush=True)
    existing={text:name for text,name in mapping.items() if (folder/name).exists() and (folder/name).stat().st_size>=500}
    manifest={'voice':'Open JTalk · Mei (HTS)','files':existing}
    (ROOT/'data/audio.js').write_text('// Bundled Japanese recordings; generated by scripts/build_audio.py.\nwindow.DEKIRU_AUDIO = '+json.dumps(manifest,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    print(f'Recordings: {len(existing)}/{len(mapping)}, {sum((folder/name).stat().st_size for name in existing.values()):,} bytes',flush=True)
    if failures:print(failures[:5]);raise SystemExit(1)
    if len(existing)<len(mapping) and not limit:raise SystemExit('Incomplete audio pack')

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--limit',type=int);parser.add_argument('--collect-only',action='store_true');args=parser.parse_args()
    texts=collect();print(f'Unique audio texts: {len(texts)}',flush=True)
    (ROOT/'.work/audio-texts.json').write_text(json.dumps(texts,ensure_ascii=False,indent=2),encoding='utf-8')
    if not args.collect_only:build(texts,args.limit)
